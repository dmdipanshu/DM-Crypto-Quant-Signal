"""Q6 prospective strategy evaluation engine.

Evaluates locked candidate strategies against genuinely prospective
observations using the same triple-barrier geometry that produced the
training targets. All operations are read-only with respect to
prospective source data.
"""

from __future__ import annotations

import hashlib
import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from crypto_engine.research.execution import (  # noqa: E402
    evaluate_triple_barrier_strategy,
)
from crypto_engine.research.prospective.storage import (  # noqa: E402
    ProspectiveStorage,
)

Q6_EVALUATION_SCHEMA_VERSION = "q6-evaluation-result.v1"


def _utc_now_iso() -> str:
    return datetime.now(UTC).isoformat()


def _sha256_json(value: Any) -> str:
    """Deterministic sha256 over a JSON-serialisable value."""
    payload = json.dumps(value, sort_keys=True, default=str).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def _candles_to_arrays(
    candles: list[dict[str, Any]],
) -> dict[str, np.ndarray]:
    """Convert normalized candle records to numpy arrays for simulation."""
    opens = np.array([float(c.get("open", 0)) for c in candles], dtype=float)
    highs = np.array([float(c.get("high", 0)) for c in candles], dtype=float)
    lows = np.array([float(c.get("low", 0)) for c in candles], dtype=float)
    closes = np.array([float(c.get("close", 0)) for c in candles], dtype=float)
    volumes = np.array([float(c.get("volume", 0)) for c in candles], dtype=float)
    timestamps = pd.DatetimeIndex([pd.Timestamp(c.get("open_time", "")) for c in candles])
    return {
        "opens": opens,
        "highs": highs,
        "lows": lows,
        "closes": closes,
        "volumes": volumes,
        "timestamps": timestamps,
        "open_times": [c.get("open_time", "") for c in candles],
        "close_times": [c.get("close_time", "") for c in candles],
        "candle_ids": [c.get("event_id", "") for c in candles],
    }


class Q6EvaluationEngine:
    """Deterministic evaluation engine for prospective strategy candidates.

    Runs triple-barrier simulation on prospective observations using locked
    candidate predictions. All results are read-only with respect to
    prospective source data.
    """

    def __init__(
        self,
        *,
        storage: ProspectiveStorage,
        candidate_lock: Any,  # CandidateLock from config module
        pt_mult: float = 2.0,
        sl_mult: float = 1.0,
        max_horizon_bars: int = 24,
        fee_bp: float = 10.0,
        spread_bp: float = 5.0,
        slippage_bp: float = 5.0,
        funding_bp_per_bar: float = 0.0,
        position_pct: float = 1.0,
        starting_equity: float = 10_000.0,
    ) -> None:
        self.storage = storage
        self.candidate_lock = candidate_lock
        self.pt_mult = pt_mult
        self.sl_mult = sl_mult
        self.max_horizon_bars = max_horizon_bars
        self.fee_bp = fee_bp
        self.spread_bp = spread_bp
        self.slippage_bp = slippage_bp
        self.funding_bp_per_bar = funding_bp_per_bar
        self.position_pct = position_pct
        self.starting_equity = starting_equity

    def evaluate_candidate(
        self,
        *,
        predictions: list[int],
        decision_mask: list[bool],
        candidate_id: str | None = None,
    ) -> dict[str, Any]:
        """Evaluate a locked candidate against prospective observations.

        Parameters
        ----------
        predictions:
            Model predictions (-1=short, 0=abstain, 1=long) for each
            prospective observation. Must be generated by the locked model
            artifact using only information available at each prediction
            timestamp.
        decision_mask:
            Boolean mask indicating which observations are eligible for
            trading decisions.
        candidate_id:
            Optional override for the candidate ID being evaluated.

        Returns
        -------
        dict with evaluation result including simulation output, accounting,
        and evaluation metadata.

        Raises
        ------
        ValueError
            If predictions/decision_mask don't align with available data,
            or if candidate lock is invalid.
        """
        if not self.candidate_lock.is_valid():
            raise ValueError(
                f"Candidate lock is invalid for {candidate_id or self.candidate_lock.candidate_id}"
            )

        cid = candidate_id or self.candidate_lock.candidate_id

        candles = self.storage.read_normalized_candles()
        if not candles:
            return {
                "schema": Q6_EVALUATION_SCHEMA_VERSION,
                "evaluation_id": f"eval-{_sha256_json({cid: 'empty', 'at': _utc_now_iso()})[:16]}",
                "candidate_id": cid,
                "candidate_lock_hash": self.candidate_lock.lock_hash,
                "evaluated_at_utc": _utc_now_iso(),
                "status": "NO_OBSERVATIONS",
                "reason": "No prospective observations available for evaluation",
                "simulation": None,
                "accounting": None,
                "trade_count": 0,
                "net_return_bp": None,
                "gross_return_bp": None,
                "profit_factor": None,
                "win_rate": None,
                "max_drawdown_bp": None,
            }

        arrays = _candles_to_arrays(candles)
        n = len(candles)

        if len(predictions) != n or len(decision_mask) != n:
            raise ValueError(
                f"Predictions ({len(predictions)}) and decision_mask ({len(decision_mask)}) "
                f"must align with {n} prospective observations"
            )

        # Run triple-barrier simulation
        sim_result = evaluate_triple_barrier_strategy(
            opens=arrays["opens"],
            highs=arrays["highs"],
            lows=arrays["lows"],
            closes=arrays["closes"],
            predictions=np.array(predictions, dtype=int),
            decision_mask=np.array(decision_mask, dtype=bool),
            timestamps=arrays["timestamps"],
            vol_at_entry=np.full(n, 0.02),  # Default 2% vol - would come from candidate config
            pt_mult=self.pt_mult,
            sl_mult=self.sl_mult,
            max_horizon_bars=self.max_horizon_bars,
            fee_bp=self.fee_bp,
            spread_bp=self.spread_bp,
            slippage_bp=self.slippage_bp,
            funding_bp_per_bar=self.funding_bp_per_bar,
            position_pct=self.position_pct,
            starting_equity=self.starting_equity,
        )

        # Build enriched result with candidate metadata
        evaluation_id = f"eval-{_sha256_json({cid: sim_result, 'at': _utc_now_iso()})[:16]}"

        result = {
            "schema": Q6_EVALUATION_SCHEMA_VERSION,
            "evaluation_id": evaluation_id,
            "candidate_id": cid,
            "candidate_lock_hash": self.candidate_lock.lock_hash,
            "evaluated_at_utc": _utc_now_iso(),
            "status": "EVALUATED",
            "reason": None,
            "simulation": sim_result,
            "prospective_dataset": {
                "storage_root": str(self.storage.root),
                "observation_count": n,
                "candle_ids": arrays["candle_ids"],
                "first_open_time": arrays["open_times"][0] if arrays["open_times"] else None,
                "last_close_time": arrays["close_times"][-1] if arrays["close_times"] else None,
            },
            "trade_count": sim_result.get("trade_count", 0),
            "net_return_bp": sim_result.get("total_net_return_bp"),
            "gross_return_bp": sim_result.get("gross_return_bp"),
            "profit_factor": sim_result.get("profit_factor"),
            "win_rate": sim_result.get("win_rate"),
            "max_drawdown_bp": sim_result.get("maximum_drawdown"),
            "expectancy_bp": sim_result.get("expectancy_bp"),
            "total_trading_costs_bp": sim_result.get("total_trading_costs_bp"),
            "fees_bp": sim_result.get("fees_bp"),
            "spread_bp": sim_result.get("spread_bp"),
            "slippage_bp": sim_result.get("slippage_bp"),
            "funding_bp": sim_result.get("funding_bp"),
            "gross_profit_bp": sim_result.get("gross_profit_bp"),
            "gross_loss_bp": sim_result.get("gross_loss_bp"),
            "net_profit_bp": sim_result.get("net_profit_bp"),
            "net_loss_bp": sim_result.get("net_loss_bp"),
            "gross_profit_factor": sim_result.get("gross_profit_factor"),
            "net_profit_factor": sim_result.get("net_profit_factor"),
            "average_trade_return_bp": sim_result.get("average_trade_return_bp"),
            "account_return_pct": sim_result.get("account_return_pct"),
            "max_drawdown_pct": sim_result.get("max_drawdown_pct"),
            "max_drawdown_bp_account": sim_result.get("max_drawdown_bp_account"),
            "final_equity": sim_result.get("final_equity"),
            "exposure_fraction": sim_result.get("exposure_fraction"),
            "turnover_equity_turns": sim_result.get("turnover_equity_turns"),
            "bars_held_total": sim_result.get("bars_held_total"),
            "cost_stress": sim_result.get("cost_stress", []),
            "skipped": sim_result.get("skipped", {}),
            "trades": sim_result.get("trades", []),
        }

        return result


def evaluate_multiple_candidates(
    *,
    storage: ProspectiveStorage,
    candidate_locks: list[Any],  # list of CandidateLock
    predictions_by_candidate: dict[str, list[int]],
    decision_masks_by_candidate: dict[str, list[bool]],
    **eval_kwargs: Any,
) -> list[dict[str, Any]]:
    """Evaluate multiple locked candidates against the same prospective data.

    Returns a list of evaluation results, one per candidate.
    """
    results: list[dict[str, Any]] = []
    for lock in candidate_locks:
        cid = (
            lock.candidate_lock.candidate_id
            if hasattr(lock, "candidate_lock")
            else lock.candidate_id
        )
        engine = Q6EvaluationEngine(
            storage=storage,
            candidate_lock=lock.candidate_lock if hasattr(lock, "candidate_lock") else lock,
            **eval_kwargs,
        )
        try:
            result = engine.evaluate_candidate(
                predictions=predictions_by_candidate.get(cid, []),
                decision_mask=decision_masks_by_candidate.get(cid, []),
                candidate_id=cid,
            )
        except ValueError as exc:
            result = {
                "schema": Q6_EVALUATION_SCHEMA_VERSION,
                "evaluation_id": f"eval-{_sha256_json({cid: str(exc), 'at': _utc_now_iso()})[:16]}",
                "candidate_id": cid,
                "candidate_lock_hash": lock.lock_hash if hasattr(lock, "lock_hash") else "",
                "evaluated_at_utc": _utc_now_iso(),
                "status": "EVALUATION_ERROR",
                "reason": str(exc),
                "simulation": None,
                "accounting": None,
                "trade_count": 0,
                "net_return_bp": None,
                "gross_return_bp": None,
                "profit_factor": None,
                "win_rate": None,
                "max_drawdown_bp": None,
            }
        results.append(result)
    return results


__all__ = [
    "Q6_EVALUATION_SCHEMA_VERSION",
    "Q6EvaluationEngine",
    "evaluate_multiple_candidates",
]
